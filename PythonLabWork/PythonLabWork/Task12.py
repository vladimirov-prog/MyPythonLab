# Задача 12. Даны катеты прямоугольного треугольника a и b. Найти его гипотенузу c и периметр P

a = float(input("Введите катет a: "))
b = float(input("Введите катет b: "))

# Считаем гипотенузу по теореме Пифагора (корень из суммы квадратов)
c = (a ** 2 + b ** 2) ** 0.5

# Считаем периметр
P = a + b + c

print(f"Гипотенуза c равна: {c}")
print(f"Периметр P равен: {P}")
