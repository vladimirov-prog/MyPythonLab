# Задача 15. Дана площадь S круга. Найти его диаметр D и длину L окружности. Значение pi = 3.14

pi = 3.14
S = float(input("Введите площадь круга S: "))

# Находим радиус (корень из S / pi)
R = (S / pi) ** 0.5

# Находим диаметр и длину окружности
D = 2 * R
L = 2 * pi * R

print(f"Диаметр круга D равен: {D}")
print(f"Длина окружности L равна: {L}")
