# Задача 13. Даны два круга с общим центром и радиусами R1 и R2. Найти площади S1, S2 и площадь кольца S3

pi = 3.14

R1 = float(input("Введите внешний радиус R1: "))
R2 = float(input("Введите внутренний радиус R2: "))

S1 = pi * (R1 ** 2)
S2 = pi * (R2 ** 2)
S3 = S1 - S2

print(f"Площадь первого круга S1 равна: {S1}")
print(f"Площадь второго круга S2 равна: {S2}")
print(f"Площадь кольца S3 равна: {S3}")
