# Задача 6. Даны длины ребер a, b, c прямоугольного параллелепипеда. Найти объем V = a*b*c и площадь поверхности S = 2*(a*b + b*c + a*c)

a = float(input("Введите длину ребра a: "))
b = float(input("Введите длину ребра b: "))
c = float(input("Введите длину ребра c: "))

V = a * b * c
S = 2 * (a * b + b * c + a * c)

print(f"Объем параллелепипеда V равен: {V}")
print(f"Площадь поверхности S равна: {S}")
