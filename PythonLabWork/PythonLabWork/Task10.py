# Задача 10. Даны два ненулевых числа. Найти сумму, разность, произведение и частное их квадратов

a = float(input("Введите первое ненулевое число a: "))
b = float(input("Введите второе ненулевое число b: "))


a2 = a ** 2
b2 = b ** 2


summ = a2 + b2
diff = a2 - b2
prod = a2 * b2
quot = a2 / b2

print(f"Сумма квадратов равна: {summ}")
print(f"Разность квадратов равна: {diff}")
print(f"Произведение квадратов равно: {prod}")
print(f"Частное квадратов равно: {quot}")
