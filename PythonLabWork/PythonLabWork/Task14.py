# Задача 14. Дана длина L окружности. Найти ее радиус R и площадь S круга. Значение pi = 3.14

pi = 3.14
L = float(input("Введите длину окружности L: "))

# Вычисляем радиус R
R = L / (2 * pi)

# Вычисляем площадь S
S = pi * (R ** 2)

print(f"Радиус круга R равен: {R}")
print(f"Площадь круга S равна: {S}")
