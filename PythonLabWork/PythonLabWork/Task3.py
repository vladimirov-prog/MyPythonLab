# Задача 3. Даны стороны прямоугольника a и b. Найти его площадь S = a * b и периметр P = 2 * (a + b)

a = float(input("Введите сторону прямоугольника a: "))
b = float(input("Введите сторону прямоугольника b: "))

S = a * b
P = 2 * (a + b)

print(f"Площадь S равна: {S}")
print(f"Периметр P равен: {P}")
